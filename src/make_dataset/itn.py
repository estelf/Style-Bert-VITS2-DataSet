"""記号の読み上げ展開と残留記号検出 (G2P 失敗ゲートの誤爆削減)。

ASR 出力に混ざりやすい記号を、pyopenjtalk-plus (学習側と同一エンジン) が読める日本語読みへ置換する。
+/- のような「読みが文脈依存 (たす/プラス/ふたつ...)」な記号は誤読リスクの方が大きいため意図的に写さない。
英語→カタカナ変換は発音辞書 (judict 等) が必要なため本パイプラインでは未実装のまま (README の既知の差分に記録)。
"""

from __future__ import annotations

# ASR 出力で頻出する記号 → 日本語読み (NFKC 後の半角/全角コードポイントで引く)
SYMBOL_READINGS: dict[str, str] = {
    "%": "パーセント",
    "‰": "パーミル",
    "℃": "度",
    "℉": "華氏度",
    "㎡": "平方メートル",
    "㎥": "立方メートル",
    "㎞": "キロメートル",
    "㎝": "センチメートル",
    "㎜": "ミリメートル",
    "㎏": "キログラム",
    "㎎": "ミリグラム",
    "㌍": "キログラム",
    "㌘": "グラム",
    "㌔": "キロ",
    "㌢": "センチメートル",
    "㌫": "パーセント",
    "№": "番号",
    "&": "アンド",
    "×": "かける",
    "÷": "わる",
    "±": "プラスマイナス",
    "①": "1",
    "②": "2",
    "③": "3",
    "④": "4",
    "⑤": "5",
    "⑥": "6",
    "⑦": "7",
    "⑧": "8",
    "⑨": "9",
    "⑩": "10",
}

# セリフに残してよい句読点・区切り (学習側 G2P が黙って処理するもの)。これ以外の記号は残留記号として数える
_ALLOWED_SYMBOLS = set("。，、！？：；・〜ー…‐–―’‘“”\"'()（）-")


def expand_symbols(text: str) -> tuple[str, int]:
    """既知の記号を日本語読みへ置換する。戻り値は (変換後テキスト, 置換回数)。"""
    n = 0
    for sym, reading in SYMBOL_READINGS.items():
        c = text.count(sym)
        if c:
            text = text.replace(sym, reading)
            n += c
    return text, n


def residual_symbols(text: str) -> int:
    """英数・かな・漢字・許可済み句読点のいずれでもない文字の数 (展開後も残る G2P リスクの可視化)。"""
    n = 0
    for ch in text:
        if ch.isspace() or ch in _ALLOWED_SYMBOLS or ch.isalnum():
            continue
        n += 1
    return n
